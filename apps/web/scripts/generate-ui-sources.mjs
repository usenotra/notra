import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const webRoot = fileURLToPath(new URL("../", import.meta.url));
const uiRoot = path.resolve(webRoot, "../../packages/ui/src");
const output = path.join(webRoot, "src/styles/ui-sources.css");
const extensions = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".mdx"];
const pending = [];
const visited = new Set();
const sources = new Set();

function collect(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collect(filename);
    } else if (extensions.includes(path.extname(filename))) {
      pending.push(filename);
    }
  }
}

function resolveSource(base) {
  return [
    ...(extensions.includes(path.extname(base)) ? [base] : []),
    ...extensions.map((extension) => `${base}${extension}`),
    ...extensions.map((extension) => path.join(base, `index${extension}`)),
  ].find((candidate) => existsSync(candidate));
}

collect(path.join(webRoot, "src"));
// These entry points may also import shared components outside src/.
for (const filename of ["source.config.ts"]) {
  const entry = path.join(webRoot, filename);
  if (existsSync(entry)) {
    pending.push(entry);
  }
}

while (pending.length > 0) {
  const filename = pending.pop();
  if (visited.has(filename)) {
    continue;
  }
  visited.add(filename);
  if (filename.startsWith(`${uiRoot}${path.sep}`)) {
    sources.add(filename);
  }
  const imports = ts.preProcessFile(readFileSync(filename, "utf8"), true, true);
  for (const { fileName: specifier } of imports.importedFiles) {
    let base;
    if (specifier.startsWith("@notra/ui/")) {
      base = path.join(uiRoot, specifier.slice("@notra/ui/".length));
    } else if (specifier.startsWith(".")) {
      base = path.resolve(path.dirname(filename), specifier);
    } else {
      continue;
    }
    if (path.extname(base) === ".css") {
      continue;
    }
    const resolved = resolveSource(base);
    if (resolved) {
      pending.push(resolved);
    } else if (
      specifier.startsWith("@notra/ui/") ||
      filename.startsWith(`${uiRoot}${path.sep}`)
    ) {
      throw new Error(
        `Cannot resolve shared UI source: ${specifier} in ${filename}`
      );
    }
  }
}

const css = [
  "/* Generated by scripts/generate-ui-sources.mjs. Do not edit by hand. */",
  ...[...sources]
    .sort()
    .map(
      (filename) =>
        `@source "${path.relative(path.dirname(output), filename).split(path.sep).join("/")}";`
    ),
  "",
].join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== css) {
    throw new Error(
      "Shared UI sources are stale. Run bun run styles:generate in apps/web."
    );
  }
} else if (!existsSync(output) || readFileSync(output, "utf8") !== css) {
  writeFileSync(output, css);
}
console.log(`Tailwind: ${sources.size} reachable shared UI source files.`);
